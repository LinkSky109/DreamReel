/**
 * 名称过滤：抽取出的实体/角色里常有一批"泛名"（人类、绝望、世界…），
 * 它们作为设定图名字太笼统、且会和正文里随处可见的词误匹配。
 */
export const GENERIC_NAMES = new Set([
  '人类', '人们', '众人', '他们', '我们', '你们', '自己', '所有', '一切', '世界', '大陆', '星球', '宇宙', '天空', '大地',
  '希望', '绝望', '死亡', '活着', '生命', '生存', '痛苦', '黑暗', '光明', '命运', '时间', '空间', '力量', '能量',
  '规则', '秩序', '文明', '社会', '城市', '废墟', '战争', '和平', '末日', '末世', '变异', '危机', '秘密', '真相',
  '恐惧', '愤怒', '孤独', '回忆', '过去', '未来', '现在', '战争', '杀戮', '食物', '水源', '金属', '机械', '系统',
])

export function isGenericName(name) {
  return !name || name.length < 2 || GENERIC_NAMES.has(name)
}

export default { GENERIC_NAMES, isGenericName }
